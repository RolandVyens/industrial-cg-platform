"""Reproduce the active Deep POD contract. Checking is the default, with no writes."""

import argparse
import hashlib
import json
from pathlib import Path
import subprocess


def generate(schema_path):
    schema = json.loads(schema_path.read_text(encoding="utf-8"))
    types = {"u32": ("uint32_t", 4, 4), "i32": ("int32_t", 4, 4),
             "u64": ("uint64_t", 8, 8), "float": ("float", 4, 4), "bool": ("bool", 1, 1)}
    parts = ["/* SPDX-FileCopyrightText: 2026 Blender Authors\n"
             " * SPDX-License-Identifier: Apache-2.0 */\n#pragma once\n\n"
             "#include <stdint.h>\n#include <stddef.h>\n",
             "// Generated by generate_deep_bounded_schema.py; edit deep_bounded_schema.json.\n",
             # Schema7's stamp uses canonical CRLF bytes so checkout newline
             # conversion cannot invalidate a correct host/device contract.
             "// Schema SHA256: " + hashlib.sha256(
                 schema_path.read_text(encoding="utf-8").replace("\n", "\r\n").encode("utf-8")
             ).hexdigest() + "\n",
             f"constexpr uint32_t DEEP_BOUNDED_SCHEMA = {schema['schema']}u;\n"]
    for record in schema["records"]:
        parts.append(f"\nstruct {record['name']} {{\n")
        offset, alignment = 0, 1
        for field in record["fields"]:
            typename, size, align = types[field["type"]]
            offset = (offset + align - 1) // align * align
            if offset != field["offset"]:
                raise ValueError(f"Incorrect offset: {record['name']}.{field['name']}")
            default = ""
            if "default" in field:
                if field["type"] != "bool" or type(field["default"]) is not bool:
                    raise ValueError("Only explicit boolean defaults are supported")
                default = " = " + str(field["default"]).lower()
            parts.append(f"  {typename} {field['name']}{default};\n")
            offset += size
            alignment = max(alignment, align)
        if (offset + alignment - 1) // alignment * alignment != record["size_bytes"]:
            raise ValueError(f"Incorrect size: {record['name']}")
        parts.append(f"}};\nstatic_assert(sizeof({record['name']}) == {record['size_bytes']});\n")
        for field in record["fields"]:
            parts.append(f"static_assert(offsetof({record['name']}, {field['name']}) == {field['offset']});\n")
    for enum in schema["enums"]:
        parts.append(f"\nenum class {enum['name']} : uint32_t {{\n")
        parts.extend(f"  {name} = {value},\n" for name, value in enum["values"].items())
        parts.append("};\n")
    return "".join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="Check the active header (default)")
    mode.add_argument("--write", action="store_true", help="Update this dedicated source worktree")
    mode.add_argument("--output", type=Path, help="Write a new preview file outside the source tree")
    args = parser.parse_args()
    directory = Path(__file__).resolve().parent
    root = directory.parents[3]
    target = directory / "deep_bounded_schema.h"
    try:
        content = generate(directory / "deep_bounded_schema.json")
        if args.write:
            branch = subprocess.check_output(
                ["git", "-C", str(root), "branch", "--show-current"], text=True).strip()
            if not branch.startswith(("feature/", "fix/", "repair/", "intake/")):
                parser.error("Writing requires a dedicated feature/fix/repair/intake worktree")
            # A linked worktree has a .git file, unlike the canonical source repository.
            if not (root / ".git").is_file():
                parser.error("Refusing to write in the canonical source checkout")
            target.write_text(content, encoding="utf-8", newline="\n")
        elif args.output:
            output = args.output.resolve()
            if output.is_relative_to(root) or output.exists():
                parser.error("Preview must be a new file outside the source tree")
            output.write_text(content, encoding="utf-8", newline="\n")
        elif target.read_text(encoding="utf-8") != content:
            parser.error("Active header differs from its schema; regenerate in the dedicated worktree")
    except (ValueError, KeyError, OSError, subprocess.CalledProcessError) as error:
        parser.error(str(error))
    print(f"Deep schema {directory / 'deep_bounded_schema.json'}: OK")


if __name__ == "__main__":
    main()
